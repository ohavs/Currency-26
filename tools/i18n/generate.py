"""Writes app/src/main/res/values*/strings.xml from base.py and translations.py.

Usage: python3 tools/i18n/generate.py app/src/main/res
Fails (without writing) when a language misses a key or its format placeholders differ from English.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from base import ROWS  # noqa: E402
from translations import TRANSLATIONS  # noqa: E402

PLACEHOLDER = re.compile(r"%(?:\d+\$)?[sd%]")


def esc(s):
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')


def placeholders(s):
    return sorted(PLACEHOLDER.findall(s))


def check():
    keys = [r[0] for r in ROWS]
    english = {r[0]: r[2] for r in ROWS}
    problems = []
    for lang, table in TRANSLATIONS.items():
        missing = [k for k in keys if k not in table]
        extra = [k for k in table if k not in english]
        if missing:
            problems.append(f"{lang}: missing {missing}")
        if extra:
            problems.append(f"{lang}: unknown {extra}")
        for k, v in table.items():
            if k in english and placeholders(v) != placeholders(english[k]):
                problems.append(f"{lang}.{k}: placeholders {placeholders(v)} != {placeholders(english[k])}")
    for key, he, en, es in ROWS:
        for lang, v in (("he", he), ("es", es)):
            if placeholders(v) != placeholders(en):
                problems.append(f"{lang}.{key}: placeholders {placeholders(v)} != {placeholders(en)}")
    return problems


def write(res, folder, header, values):
    os.makedirs(os.path.join(res, folder), exist_ok=True)
    with open(os.path.join(res, folder, "strings.xml"), "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n')
        f.write(f"<!-- {header}. Generated by tools/i18n/generate.py - edit the tables there, not this file. -->\n<resources>\n")
        for key, _, _, _ in ROWS:
            f.write(f'    <string name="{key}">{esc(values[key])}</string>\n')
        f.write("</resources>\n")


NAMES = {"ar": "Arabic", "ru": "Russian", "fr": "French", "de": "German", "pt": "Portuguese", "it": "Italian",
         "tr": "Turkish", "zh": "Chinese (Simplified)", "ja": "Japanese", "hi": "Hindi"}


def main():
    res = sys.argv[1]
    problems = check()
    if problems:
        print("\n".join(problems))
        sys.exit(1)
    write(res, "values", "English (default for languages the app does not translate)", {r[0]: r[2] for r in ROWS})
    write(res, "values-iw", "Hebrew", {r[0]: r[1] for r in ROWS})
    write(res, "values-he", "Hebrew (same as values-iw; newer devices may resolve either qualifier)", {r[0]: r[1] for r in ROWS})
    write(res, "values-es", "Spanish", {r[0]: r[3] for r in ROWS})
    for lang, table in TRANSLATIONS.items():
        write(res, f"values-{lang}", NAMES.get(lang, lang), table)
    print(f"{len(ROWS)} strings x {4 + len(TRANSLATIONS)} folders")


if __name__ == "__main__":
    main()
